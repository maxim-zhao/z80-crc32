.section "Z80Test version" force
  ; Set page count
  ld b, 2

  ; Init CRC state in shadow regs
  exx
    ld bc, $ffff
    ld d, b
    ld e, c
  exx

  ld de, $4000 ; Initial address
  
_bank_loop:
  push bc
    
    ; Unrolling 64 times means we need to loop only 256 times to cover 16KB
.ifdef UNROLL
.define UNROLL_COUNT 16*1024/256
    ld b, 0 ; to get 256 loops
.else
    ld b, <(16*1024)
    ld c, >(16*1024)
.endif
    
_bytes_in_bank_loop:

.ifdef UNROLL
.repeat UNROLL_COUNT
.endif
    ld a, (de)
    inc de

    ; CRC update.
    exx
      xor e

      ld l, a
      ld h, >crctable

      ld a, (hl)
      xor d
      ld e, a
      inc h

      ld a, (hl)
      xor c
      ld d, a
      inc h

      ld a, (hl)
      xor b
      ld c, a
      inc h

      ld b, (hl)
    exx

.ifdef UNROLL
.endr
    dec b
    jp nz, _bytes_in_bank_loop
.else
    djnz _bytes_in_bank_loop
    dec c
    jp nz, _bytes_in_bank_loop
.endif
  pop bc

  dec b
  jp nz, _bank_loop

  ; Invert all bits when done
  exx
    ld hl, RAM_CRC
    ld a, e
    cpl
    ld (hl), a
    inc hl
    ld a, d
    cpl
    ld (hl), a
    inc hl
    ld a, c
    cpl
    ld (hl), a
    inc hl
    ld a, b
    cpl
    ld (hl), a
  exx
  ret ; to end the test

.ends

